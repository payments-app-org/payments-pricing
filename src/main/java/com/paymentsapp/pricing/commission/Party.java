package com.paymentsapp.pricing.commission;

// Откуда списываем и куда зачисляем — от этого зависит тариф
public enum Party {
    WALLET,             // «Мой кошелёк»
    OUR_CARD,           // карта нашего банка
    PARTNER_CARD,       // карта партнёрского сервиса
    OTHER_BANK_CARD,    // карта другого банка
    OPERATOR_ACCOUNT,   // лицевой счёт мобильного оператора
    SBP,                // перевод через СБП
    MOBILE,             // оплата сотовой связи
    ABROAD,             // перевод за рубеж
    QR,                 // оплата по QR
    LEGAL_ENTITY,       // юрлицо в другом банке
    OUR_LEGAL_ENTITY,   // юрлицо со счётом в нашем банке
    GOV,                // бюджет: госуслуги, штрафы, налоги
    TRANSPORT,          // транспорт: проездные, парковки, платные дороги, такси, билеты
    GAMES,              // игры и сервисы
    FOREIGN_MOBILE,     // сотовая связь за рубежом
    EMONEY,             // электронные деньги (ЮMoney)
    EDUCATION,          // образование: школы, кружки, карта школьника
    SHOPS,              // интернет-магазины
    TRAVEL,             // путешествия: билеты, туры
    INSURANCE           // страхование
}
