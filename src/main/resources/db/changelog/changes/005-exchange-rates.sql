-- Курсы валют для переводов за рубеж. Комиссию за такие переводы не берём — доход банка в наценке на курс.
-- cbr_rate — рублей за единицу валюты (официальный курс), sell_rate — наш курс продажи = cbr_rate × (1 + markup).
-- Пока значения статичные; позже их будет обновлять задача из API ЦБ.
CREATE TABLE exchange_rates (
    currency          VARCHAR(3)     PRIMARY KEY,
    name_ru           VARCHAR(50)    NOT NULL,
    symbol            VARCHAR(5)     NOT NULL,
    cbr_rate          NUMERIC(19, 6) NOT NULL CHECK (cbr_rate > 0),
    markup_percent    NUMERIC(5, 2)  NOT NULL DEFAULT 4.5,
    sell_rate         NUMERIC(19, 6) GENERATED ALWAYS AS (round(cbr_rate * (1 + markup_percent / 100), 6)) STORED,
    updated_at        TIMESTAMPTZ    NOT NULL DEFAULT now()
);

